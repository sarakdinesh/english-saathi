// Adds human voice recordings to the app.
//   node --experimental-strip-types scripts/import-voice.ts <folder>
// File names follow docs/voice-recording-list.md: say-<situation>-<n> for
// phrasebook sentences, tip-… for pronunciation-tip words. Each clip is
// trimmed of silence, volume-normalised and converted to AAC in assets/voice/,
// then src/data/voiceClips.ts is regenerated. Needs ffmpeg. Re-running replaces
// clips with the same name and keeps the others.
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { load } from "./lib.ts";

// Every recordable name → the exact app text it replaces.
export function clipTexts(): Map<string, string> {
  const map = new Map<string, string>();
  const { drillCards, sounds } = load("src/data/speaking.ts");
  for (const c of drillCards) map.set(c.id, c.en);
  const doc = fs.readFileSync("docs/voice-recording-list.md", "utf8");
  for (const m of doc.matchAll(/^\| (tip-[\w-]+) \| ([^|]+?) \|/gm)) map.set(m[1], m[2].trim());
  // Tip words must still exist in the app, or the clip would never play.
  const words = new Set(sounds.flatMap((x: any) => x.pairs.map((p: any) => p.en)));
  for (const [name, text] of map) if (name.startsWith("tip-") && !words.has(text)) map.delete(name);
  return map;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const src = process.argv[2];
  if (!src || !fs.statSync(src, { throwIfNoEntry: false })?.isDirectory()) {
    console.error("Usage: node --experimental-strip-types scripts/import-voice.ts <folder>");
    process.exit(1);
  }
  const texts = clipTexts();
  const out = "assets/voice";
  fs.mkdirSync(out, { recursive: true });
  const unknown: string[] = [];
  for (const file of fs.readdirSync(src)) {
    const name = path.parse(file).name;
    if (!texts.has(name)) {
      if (!file.startsWith(".")) unknown.push(file);
      continue;
    }
    execFileSync("ffmpeg", [
      "-y", "-loglevel", "error", "-i", path.join(src, file),
      // Trim leading/trailing silence, then even out loudness.
      "-af",
      "silenceremove=start_periods=1:start_threshold=-45dB,areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse,loudnorm=I=-16:TP=-1.5",
      "-ac", "1", "-c:a", "aac", "-b:a", "64k",
      path.join(out, `${name}.m4a`),
    ]);
    console.log(`✓ ${name}`);
  }
  const have = fs
    .readdirSync(out)
    .map((f) => path.parse(f).name)
    .filter((n) => texts.has(n))
    .sort();
  const lines = have.map(
    (n) => `  ${JSON.stringify(texts.get(n))}: require("../../assets/voice/${n}.m4a"),`,
  );
  fs.writeFileSync(
    "src/data/voiceClips.ts",
    `// Generated by scripts/import-voice.ts — do not edit by hand.
// Exact English text → recorded human clip in assets/voice/. Text without a
// clip uses the phone's voice.
export const voiceClips: Record<string, number> = {${lines.length ? `\n${lines.join("\n")}\n` : ""}};
`,
  );
  console.log(`${have.length} clips in the app.`);
  if (unknown.length) console.log(`Skipped (name not in the recording list): ${unknown.join(", ")}`);
}
