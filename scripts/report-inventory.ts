// Generates docs/curriculum-inventory.md: an audit of every unit, lesson,
// exercise, role-play and checkpoint, computed from the bundled content.
// Run: npm run report:inventory
import fs from "node:fs";
import { load } from "./lib.ts";

const cur = load("src/curriculum/index.ts");
const { lessons } = load("src/data/course.ts");
const { placementQuestions, foundationQuestions } = load("src/curriculum/placement.ts");
const kits = cur.kits;
const lessonOf = (id: string) => lessons.find((l: any) => l.id === id);

// Provisional CEFR labels. These describe the *kind* of language a unit
// practises, judged from its content. They are NOT assessed levels, nothing in
// the app tests against them, and they are unreviewed by a qualified teacher.
const cefr: Record<string, string> = {
  f1: "pre-A1", f2: "pre-A1", f3: "pre-A1", f4: "pre-A1 / A1", r0: "pre-A1",
  b1: "A1", b2: "A1", b3: "A1", b4: "A1", b5: "A1", b6: "A1", b7: "A1", b8: "A1",
  b8p: "A1 / A2", b9: "A2", b10: "A2", b11: "A1 / A2",
  i1: "A2 / B1", i2: "B1", i3: "B1", i4: "B1", i5: "B1", i6: "B1", i7: "B1",
  i8: "B1", i9: "B1 / B2", i10: "B1",
};

const words = (s: string) => (s.toLowerCase().match(/[a-z]+(?:'[a-z]+)?/g) ?? []) as string[];
const unitText = (u: any) =>
  u.lessons.flatMap((id: string) => {
    const l = lessonOf(id), k = kits[id];
    return [l.title, l.formula, ...l.examples.map((e: any) => e.en), ...(k?.conv ?? []).map((c: any) => c.en), ...(k?.patterns ?? [])];
  });
const countBy = <T,>(xs: T[], f: (x: T) => string) => {
  const m: Record<string, number> = {};
  for (const x of xs) m[f(x)] = (m[f(x)] ?? 0) + 1;
  return m;
};
const skills = ["understand", "gap", "en-mr", "mr-en", "response", "listen", "build"];
const mix = (xs: any[]) => skills.map((s) => `${s} ${xs.filter((e) => e.skill === s).length}`).join(" · ");

const out: string[] = [];
const push = (...l: string[]) => out.push(...l);

// ---------- Totals --------------------------------------------------------
const allEx = Object.values(kits).flatMap((k: any) => k.ex);
const cpEx = cur.units.flatMap((u: any) => u.checkpoint?.ex ?? []);
const pathCount = (p: string) => cur.units.filter((u: any) => u.path === p);
push(
  "# Curriculum inventory and audit",
  "",
  "Generated by `npm run report:inventory` from the bundled content, so the numbers are exact. Everything about **language quality is unreviewed**: automated checks prove structure only. CEFR labels below are **provisional descriptions of content**, not assessed levels; the app does not certify any proficiency level.",
  "",
  "## Totals",
  "",
  "| Measure | Count |",
  "| --- | ---: |",
  `| Units | ${cur.units.length} (${pathCount("foundation").length} Foundation, ${pathCount("reading").length} Reading, ${pathCount("beginner").length} Beginner, ${pathCount("intermediate").length} Intermediate) |`,
  `| Lessons | ${lessons.length}, every one with a full kit |`,
  `| Lesson exercises | ${allEx.length} (${mix(allEx)}) |`,
  `| Checkpoints / questions | ${cur.units.filter((u: any) => u.checkpoint).length} / ${cpEx.length} |`,
  `| Lesson role-plays | ${cur.rolePlays.length} |`,
  `| Long speaking talks | ${cur.talks.length} (intermediate only) |`,
  `| Placement questions | ${foundationQuestions.length} + ${placementQuestions.length} |`,
  `| Useful expressions (conversation lines, revisable) | ${cur.expressions.length} |`,
  "",
);

// ---------- Per path / unit ----------------------------------------------
const seenWords: Record<string, Set<string>> = {};
for (const path of ["foundation", "reading", "beginner", "intermediate"]) {
  const title: Record<string, string> = {
    foundation: "Foundation (Level 0)", reading: "Reading foundations (optional)",
    beginner: "Beginner", intermediate: "Intermediate",
  };
  push(`## ${title[path]}`, "");
  const units = pathCount(path);
  seenWords[path] = new Set();
  units.forEach((u: any, i: number) => {
    const ks = u.lessons.map((id: string) => kits[id]);
    const ex = ks.flatMap((k: any) => k.ex);
    const rp = ks.map((k: any) => k.rp);
    const learnerTurns = rp.reduce((n: number, r: any) => n + r.turns.filter((t: any) => t.who === "you").length, 0);
    const texts = unitText(u);
    const unitWords = new Set(texts.flatMap(words));
    const fresh = [...unitWords].filter((w) => !seenWords[path].has(w) && w.length > 1);
    unitWords.forEach((w) => seenWords[path].add(w));
    const patterns = [...new Set(ks.flatMap((k: any) => k.patterns))];
    const prev = units[i - 1];
    push(
      `### ${u.id} · ${u.en}`,
      "",
      `- **Title (Marathi):** ${u.title}`,
      `- **Provisional CEFR description:** ${cefr[u.id] ?? "unmapped"}`,
      `- **Practical outcome:** ${u.outcome[0]}`,
      `- **Outcome (Marathi):** ${u.outcome[1]}`,
      `- **Prerequisites:** ${prev ? `previous unit \`${prev.id}\` (order only; no unit is locked)` : path === "foundation" ? "none (absolute beginner)" : "none enforced"}`,
      `- **Lessons (${u.lessons.length}):** ${u.lessons.map((id: string) => `\`${id}\``).join(", ")}`,
      `- **Sentence patterns introduced (${patterns.length}):** ${patterns.slice(0, 12).map((p) => `“${p}”`).join("; ")}${patterns.length > 12 ? "; …" : ""}`,
      `- **English word types appearing for the first time in this path (${fresh.length}):** ${fresh.slice(0, 24).join(", ")}${fresh.length > 24 ? ", …" : ""}`,
      `- **Listening opportunities:** ${ex.filter((e: any) => e.skill === "listen").length} audio questions, ${ks.reduce((n: number, k: any) => n + k.conv.length, 0)} audio-playable conversation lines`,
      `- **Speaking opportunities:** ${u.lessons.length} personal speaking tasks, ${rp.length} role-plays (${learnerTurns} learner turns)${u.checkpoint ? ", 1 checkpoint speaking task" : ""}${path === "intermediate" && i === units.length - 1 ? `; long talks available: ${cur.talks.length}` : ""}`,
      `- **Exercises (${ex.length}):** ${mix(ex)}`,
      `- **Assessment coverage:** ${u.checkpoint ? `checkpoint with ${u.checkpoint.ex.length} questions in a new situation (${mix(u.checkpoint.ex)})` : "no checkpoint (optional unit)"}`,
      `- **Editorial review:** machine-checked structure only; independent Marathi/English teacher review **pending**${path === "foundation" ? " (specific flags: docs/foundation-linguistic-review.md)" : ""}`,
      "",
      "| Lesson | Title | Exercises | Skill mix | Role-play turns |",
      "| --- | --- | ---: | --- | ---: |",
      ...u.lessons.map((id: string) => `| \`${id}\` | ${lessonOf(id).title} | ${kits[id].ex.length} | ${mix(kits[id].ex)} | ${kits[id].rp.turns.length} |`),
      "",
    );
  });
}

// ---------- Competency map ------------------------------------------------
type Comp = [name: string, re: RegExp];
const comps: Comp[] = [
  ["Alphabet, letter names", /alphabet|letters? a to|letter names/i],
  ["Letter sounds, phonics, blending", /phonics|blend|letter sounds|cvc|short vowel/i],
  ["Digraphs, silent letters, spelling patterns", /digraph|silent|spelling pattern/i],
  ["Numbers, days, months, time, colours", /numbers|days|months|colours|telling the time|time of day/i],
  ["Family, objects, classroom English", /family|things around|classroom/i],
  ["Pronouns", /\bpronouns?\b|i, you, he/i],
  ["Plurals and nouns", /plural/i],
  ["Adjectives / describing words", /describ(e|ing) words|adjective/i],
  ["Articles a / an / the", /\ba or an\b|articles|when to use the/i],
  ["Prepositions (in / on / at, places)", /in, on and at|places in town|near \/ next to/i],
  ["am / is / are", /am, is & are|am \/ is \/ are/i],
  ["was / were (past of be)", /was and were|past of be|was \/ were \+ (noun|adjective|place)/i],
  ["have / has, do / does", /have and has|have\/has|do \/ does/i],
  ["Present simple (routine)", /daily routine|how often|verb-s/i],
  ["Present continuous", /what are you doing|verb-ing/i],
  ["Basic questions and negatives", /question words|yes\/no|negatives|saying no/i],
  ["Past simple", /yesterday|past verb|did \+ base/i],
  ["Past simple: regular -ed and irregular verb forms taught as a set", /irregular verbs?|regular past|\-ed endings|past participle list/i],
  ["Future: going to / will", /going to|will & won/i],
  ["Present perfect", /present perfect|have \/ has \+ past participle/i],
  ["Past continuous, used to", /past continuous|used to/i],
  ["Modals: can, should, must, may, might", /can & cannot|should|must|may & might|could/i],
  ["Comparatives and superlatives", /compare two|-er \/ more/i],
  ["Conjunctions / connectors", /connect your thoughts|because|first, then/i],
  ["Conditionals", /conditionals|if \+ present/i],
  ["Passive voice", /passive/i],
  ["Reported speech", /reported speech|said that|told me that/i],
  ["Relative clauses (who / which / that)", /relative clause|\bwho\b.*\bwhich\b/i],
  ["Phrasal verbs and collocations", /phrasal|collocation/i],
  ["Quantity: some / any / much / many", /some \/ any|much \/ many|countable|a lot of/i],
  ["Imperatives and instructions", /imperative|instruction/i],
  ["Practical scenes: shop, restaurant, directions, travel, phone", /at the shop|restaurant|directions|travel:|phone call/i],
  ["Doctor / appointments / complaints", /clinic|appointment|complaint/i],
  ["Workplace and interviews", /interview|meeting|work update|work calls/i],
  ["Presentations and talks", /presentation|one-minute|talk/i],
  ["Pronunciation: stress and problem sounds", /word stress|sounds to practise/i],
  ["Short written messages / emails (writing production)", /\bemail\b|written message|text message|short message/i],
  ["Paragraph writing", /paragraph/i],
  ["Idioms and formal/informal register", /idiom|register|formal/i],
];
push("## Competency coverage map", "", "Which requested competencies have a lesson that is *about* them, found by matching lesson titles, formulas, patterns and examples. A competency can still be touched in passing elsewhere; **no lesson** means it is not taught as a topic.", "", "| Competency | Lessons about it | Status |", "| --- | --- | --- |");
const gaps: string[] = [];
for (const [name, re] of comps) {
  const hit = lessons.filter((l: any) => {
    const k = kits[l.id];
    return re.test([l.title, l.subtitle, l.formula, ...(k?.patterns ?? [])].join(" | "));
  });
  if (!hit.length) gaps.push(name);
  push(`| ${name} | ${hit.length ? hit.slice(0, 6).map((l: any) => `\`${l.id}\``).join(", ") + (hit.length > 6 ? ", …" : "") : "—"} | ${hit.length === 0 ? "**no lesson**" : hit.length === 1 ? "one lesson (thin)" : "covered"} |`);
}
push("", `**Not taught as a topic (${gaps.length}):** ${gaps.join("; ")}.`, "");

// ---------- Repetition and balance ----------------------------------------
push("## Repetition and balance checks", "");
const byPrompt = countBy([...allEx, ...cpEx], (e: any) => (e.prompt + "|" + (e.audio ?? "")).toLowerCase());
const dupPrompts = Object.entries(byPrompt).filter(([, n]) => n > 1);
push(`- Identical exercise prompts used more than once: **${dupPrompts.length}**${dupPrompts.length ? " — " + dupPrompts.slice(0, 8).map(([p, n]) => `“${p.slice(0, 50)}” ×${n}`).join("; ") + (dupPrompts.length > 8 ? "; …" : "") : ""}.`);
const convLines = Object.entries(kits).flatMap(([id, k]: any) => k.conv.map((c: any) => [id, c.en.toLowerCase()]));
const byLine = countBy(convLines, (x: any) => x[1]);
const dupLines = Object.entries(byLine).filter(([, n]) => n > 1);
push(`- Conversation lines repeated verbatim across lessons: **${dupLines.length}**${dupLines.length ? " — " + dupLines.slice(0, 6).map(([p, n]) => `“${p.slice(0, 45)}” ×${n}`).join("; ") : ""}.`);
const byPat = countBy(Object.values(kits).flatMap((k: any) => [...new Set(k.patterns)] as string[]), (p: string) => p.toLowerCase());
const reusedPat = Object.entries(byPat).filter(([, n]) => n > 2);
push(`- Sentence patterns appearing in 3+ lessons: **${reusedPat.length}**${reusedPat.length ? " — " + reusedPat.slice(0, 6).map(([p, n]) => `“${p.slice(0, 40)}” ×${n}`).join("; ") : ""}.`);
const lessonsMissing = (skill: string) => lessons.filter((l: any) => !kits[l.id].ex.some((e: any) => e.skill === skill)).length;
push(`- Lessons with **no** listening question: ${lessonsMissing("listen")} of ${lessons.length}; no sentence-building (arrange) question: ${lessonsMissing("build")}; no gap-fill: ${lessonsMissing("gap")}; no reply-selection question: ${lessonsMissing("response")}.`);
push("", "| Path | Lessons | Exercises | Listening | Sentence building | Gap-fill | Reading (understand) | Reply selection | Meaning (en↔mr) |", "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |");
for (const path of ["foundation", "reading", "beginner", "intermediate"]) {
  const ex = pathCount(path).flatMap((u: any) => u.lessons.flatMap((id: string) => kits[id].ex));
  const n = (s: string[]) => ex.filter((e: any) => s.includes(e.skill)).length;
  push(`| ${path} | ${pathCount(path).reduce((a: number, u: any) => a + u.lessons.length, 0)} | ${ex.length} | ${n(["listen"])} | ${n(["build"])} | ${n(["gap"])} | ${n(["understand"])} | ${n(["response"])} | ${n(["en-mr", "mr-en"])} |`);
}
push("");

// ---------- Gap summary ---------------------------------------------------
push(
  "## Gaps identified",
  "",
  "1. **Past simple was one compact lesson (`yesterday`).** There was no lesson on `was/were`, and regular `-ed` forms (with their three pronunciations) and common irregular verbs were not taught as sets. Storytelling (`i3`), interviews (`i6`) and the present-perfect contrast (`i8`) all depend on this. *Highest-priority gap in the sequence as found; **addressed by the new unit `b8p`** (4 lessons, checkpoint). `yesterday` in `b9` now acts as consolidation.*",
  "2. **Writing production is not covered.** No lesson asks the learner to write a message, email or paragraph; the only written-style exercise is arranging given words. Free writing cannot be auto-checked, so this needs a self-check/checklist design.",
  "3. **Imperatives, reported speech and relative clauses have no lesson, and quantity words (some/any/much/many) appear only in passing (`no-article`).**",
  "4. **Nothing above the B1 range:** no B2, C1 or C2 content exists.",
  "5. **Listening is single short sentences read by the device voice;** there are no longer passages or varied speakers, and the voice is not guaranteed to be an Indian-English or any specific accent.",
  "6. **Speaking is self-reported** (no recognition, no scoring) and Foundation has no long talk.",
  "7. **Some Foundation topics duplicate Beginner lessons** (numbers, days, family, time); this is intentional first exposure but means two lessons cover similar ground.",
  "",
  "## Provisional CEFR description of the existing content",
  "",
  "A cautious reading of what each stage *practises*, from the unit table above. The labels are **provisional and unreviewed**; they are not outcomes of any test, and completing a unit or scoring well in the app does not show that a learner has reached a CEFR level.",
  "",
  "| Stage | Units | Provisional description |",
  "| --- | --- | --- |",
  "| Foundation | f1–f4, r0 | pre-A1: alphabet, sounds, first words |",
  "| Beginner core | b1–b8 | A1-type language: greetings, family, time, am/is/are, have/can, simple questions, routines, now |",
  "| Beginner upper | b8p, b9–b11 | A1/A2-type: past, future, requests, everyday scenes, clarification |",
  "| Intermediate | i1–i10 | A2+/B1-type: connected answers, experiences, opinions, work, problems, modals, conditionals, passive |",
  "| Not covered | — | B2, C1, C2 |",
  "",
);

fs.writeFileSync("docs/curriculum-inventory.md", out.join("\n") + "\n");
console.log(`Wrote docs/curriculum-inventory.md (${cur.units.length} units, ${lessons.length} lessons, ${allEx.length} exercises, ${cpEx.length} checkpoint questions, ${gaps.length} competencies not taught).`);
