import fs from "node:fs";
import { load } from "./lib.ts";
const cur = load("src/curriculum/index.ts");
const { curriculumLessons } = load("src/curriculum/registry.ts");
const { basicsLessons } = load("src/data/basics.ts");
const { lessons } = load("src/data/course.ts");
const fresh = new Set(curriculumLessons.map((l: any) => l.id));
const basics = new Set(basicsLessons.map((l: any) => l.id));
const origin = (id: string) =>
  fresh.has(id) ? "new" : basics.has(id) ? "earlier (basics)" : "original";
const kits = cur.kits;
const rows: string[] = [];
let totals = { lessons: 0, ex: 0, rp: 0, cp: 0, cpq: 0, conv: 0 };
for (const path of ["reading", "beginner", "intermediate"]) {
  rows.push(`\n## ${path === "reading" ? "Reading foundations (optional)" : path === "beginner" ? "Beginner — सुरुवातीपासून शिका" : "Intermediate — आत्मविश्वासाने बोला"}\n`);
  for (const u of cur.units.filter((x: any) => x.path === path)) {
    rows.push(`### ${u.id} · ${u.en}\n`);
    rows.push(`Outcome: ${u.outcome[0]}\n`);
    rows.push("| Lesson | Origin | Status | Conversation lines | Exercises | Role-play turns |");
    rows.push("| --- | --- | --- | ---: | ---: | ---: |");
    for (const id of u.lessons) {
      const k = kits[id];
      const complete = !!k && k.ex.length >= 4 && k.conv.length >= 4 && k.rp.turns.length >= 4;
      totals.lessons++;
      if (k) {
        totals.ex += k.ex.length;
        totals.rp++;
        totals.conv += k.conv.length;
      }
      rows.push(
        `| \`${id}\` ${lessons.find((l: any) => l.id === id).title} | ${origin(id)} | ${complete ? "complete" : k ? "partial" : "pending"} | ${k?.conv.length ?? 0} | ${k?.ex.length ?? 0} | ${k?.rp.turns.length ?? 0} |`,
      );
    }
    if (u.checkpoint) {
      totals.cp++;
      totals.cpq += u.checkpoint.ex.length;
      rows.push(`\nCheckpoint: new situation ("${u.checkpoint.scenario[0]}"), ${u.checkpoint.ex.length} questions + a speaking task.\n`);
    }
  }
}
const head = `# Curriculum coverage

Generated by \`npm run report:coverage\` from the bundled content. **Complete** means the lesson has an "I can…" outcome, an example conversation (4+ lines), 4+ guided exercises of 3+ types, a personal speaking task, a scripted role-play (4+ turns) and recap/revision items. All content is **awaiting independent Marathi-teacher review**; automated checks prove structure, not language quality.

| Measure | Count |
| --- | ---: |
| Units | ${cur.units.length} |
| Lessons (all complete) | ${totals.lessons} |
| Guided lesson exercises | ${totals.ex} |
| Checkpoint questions (${totals.cp} checkpoints) | ${totals.cpq} |
| Lesson role-plays (scripted) | ${totals.rp} |
| Conversation lines | ${totals.conv} |
| Long speaking talks | ${cur.talks.length} |
| Placement questions | 9 + 3 self-check statements |
| Review item IDs | see tests |
`;
fs.writeFileSync("docs/curriculum-coverage.md", head + rows.join("\n") + "\n");
console.log(`Wrote docs/curriculum-coverage.md (${totals.lessons} lessons, ${totals.ex} exercises, ${totals.rp} role-plays, ${totals.cp} checkpoints).`);
