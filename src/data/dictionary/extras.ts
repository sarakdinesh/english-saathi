export const phrasalVerbs: Phrasal[] = PHRASAL.trim()
  .split("\n")
  .map((l) => {
    const [en, mr, ex] = l.split("|").map((x) => x.trim());
    return { en, mr, ex };
  })
  .sort((a, b) => a.en.localeCompare(b.en, "en"));

export const opposites: Opposite[] = OPPOSITES.trim()
  .split("\n")
  .map((l) => {
    const [a, b, mr] = l.split("|").map((x) => x.trim());
    return { a, b, mr };
  })
  .sort((x, y) => x.a.localeCompare(y.a, "en"));
